function ExpectName($parent, $id, $expected) {
    try { $null = Wait-Ui "$id = $expected" { (ById $parent $id).Current.Name -ceq $expected } }
    catch { throw "Expected '$expected' for $id, got '$((ById $parent $id).Current.Name)' (window '$($main.Current.Name)', notice '$((ById $main 'Notice').Current.Name)')." }
}
