{
    private static readonly UTF8Encoding Utf8 = new(false, true);
    private static readonly string[] LegacyTools = ["list_projects", "get_project_snapshot", "search_project_knowledge",
        "get_knowledge_history", "submit_knowledge_commit"];
    internal sealed record Existing(string Label, string? Block = null, string[]? ToolLimit = null, Guid? Endpoint = null,
        string? RelocatedBlock = null, string? Command = null);

    internal static string Format(string command, IReadOnlyList<string> args, IReadOnlyList<string> names, bool automatic = false)
    {
        // Preserve hashes of existing managed blocks. JSON uses UTF-16 escapes for emoji, which TOML rejects.
        static string Quote(string value)
        {
            if (!value.Any(char.IsSurrogate)) return JsonSerializer.Serialize(value, DesktopJson.Default.String);
            var text = new StringBuilder("\"");
            foreach (var scalar in value.EnumerateRunes())
            {
                if (!scalar.IsBmp) text.Append(scalar.ToString());
                else
                {
                    var escaped = JsonSerializer.Serialize((char)scalar.Value, DesktopJson.Default.Char);
                    text.Append(escaped, 1, escaped.Length - 2);
                }
            }
            return text.Append('"').ToString();
        }
        static string Array(IReadOnlyList<string> values) => "[" + string.Join(", ", values.Select(Quote)) + "]";
        var body = $"[mcp_servers.projecthub]\ncommand = {Quote(command)}\nargs = {Array(args)}";
        if (automatic) body = "# Access follows the current project grant and workspace endpoints.\n" + body;
        else body += $"\nenabled_tools = {Array(names)}";
        var hash = Convert.ToHexString(SHA256.HashData(Utf8.GetBytes(body)));
        return $"# Generated by ProjectHub Edge {hash}\n{body}";
    }

    internal static string ConfigPath(LocalBinding binding)
    {
        var parent = Path.Combine(binding.LocalPath, ".codex");
        var file = Path.Combine(parent, "config.toml");
        CheckPath(file);
        return file;
    }

    internal static string Status(LocalBinding binding, string state) => Read(binding, state).Label;

    internal static Existing Read(LocalBinding binding, string state)
    {
        try
        {
            var file = ConfigPath(binding);
            var text = File.Exists(file) ? Decode(File.ReadAllBytes(file)) : "";
            return Inspect(text, binding, state);
        }
        catch (Exception e) when (e is IOException or InvalidDataException or UnauthorizedAccessException or DecoderFallbackException or TomlException)
        { return new(UiLanguage.Message("项目配置无法读取或 TOML 格式有误，请手动核对。"), ""); }
    }

    internal sealed class LinkedPathException(string path) : IOException(UiLanguage.Message("配置或 Skill 路径经过链接，请手动核对：") + path);

    internal static void CheckPath(string path)
    {
        for (var item = new FileInfo(Path.GetFullPath(path)) as FileSystemInfo; item != null;
             item = item is FileInfo file ? file.Directory : ((DirectoryInfo)item).Parent)
            if (item.LinkTarget != null || (item.Attributes != (FileAttributes)(-1) && item.Attributes.HasFlag(FileAttributes.ReparsePoint)))
                throw new LinkedPathException(item.FullName);
    }

    internal static string Decode(byte[] bytes) =>
        Utf8.GetString(bytes.AsSpan().StartsWith(Encoding.UTF8.Preamble) ? bytes.AsSpan(Encoding.UTF8.Preamble.Length) : bytes);

    internal static FileStream? OpenConfig(string path)
    {
        try { return File.Open(path, FileMode.Open, FileAccess.Read, FileShare.Read | FileShare.Delete); }
        catch (IOException ex) when (ex is FileNotFoundException or DirectoryNotFoundException)
        {
            // A reachable parent proves the file is missing. An offline drive or share is still pending.
            for (var dir = Path.GetDirectoryName(path); dir != null; dir = Path.GetDirectoryName(dir))
            {
                try
                {
                    if (!File.GetAttributes(dir).HasFlag(FileAttributes.Directory))
                        throw new IOException(UiLanguage.Text("配置所在路径不是目录。", "The configuration path is not a directory."));
                    return null;
                }
                catch (IOException missing) when (missing is FileNotFoundException or DirectoryNotFoundException) { }
            }
            throw;
        }
    }

    internal static Existing Inspect(string text, LocalBinding binding, string state)
    {
        var root = TomlSerializer.Deserialize(text, CodexToml.Default.TomlTable)!;
        if (!root.TryGetValue("mcp_servers", out var value)) return new(UiLanguage.Message("当前目录尚未配置脉络。"));
        if (value is not TomlTable servers) throw new InvalidDataException("mcp_servers 的配置格式不正确。");
        if (!servers.TryGetValue("projecthub", out var entry)) return new(UiLanguage.Message("当前目录尚未配置脉络。"));
        var custom = UiLanguage.Message("当前目录已有同名自定义配置，请手动核对。");
        if (entry is not TomlTable table || !table.TryGetValue("command", out var c) || c is not string command
            || !table.TryGetValue("args", out var a) || a is not TomlArray argsArray)
            return new(custom, "");
        var args = argsArray.OfType<string>().ToArray();
        if (args.Length != argsArray.Count || args.Length < 9 || args[0] != "mcp-stdio"
            || !args[1].Equals("--state") || !EdgeStatePaths.Same(args[2], state)
            || args[3] != "--project" || !Guid.TryParse(args[4], out var project) || project != binding.ProjectId
            || args[5] != "--binding" || !Guid.TryParse(args[6], out _)
            || args[7] != "--mode") return new(custom, "");
        string? Option(string key)
        {
            int i = Array.IndexOf(args, key);
            return i >= 0 && i + 1 < args.Length ? args[i + 1] : null;
        }
        if (Option("--workspace") is { } workspace && (!Guid.TryParse(workspace, out var workspaceId) || workspaceId != binding.WorkspaceId))
            return new(custom, "");
        string? Relocate(string[] tools, bool automatic = false)
        {
            var current = GlobalCodexAccess.CurrentCommand;
            var kind = EdgeInstallCommand.Classify(command, current);
            if (kind == EdgeCommandKind.Unknown) return null;
            if (args[2].Equals(state, StringComparison.OrdinalIgnoreCase) && current.Equals(command, StringComparison.OrdinalIgnoreCase)) return null;
            var updated = (string[])args.Clone();
            updated[2] = state;
            return Format(current, updated, tools, automatic);
        }
        Guid? endpoint = Guid.TryParse(Option("--endpoint"), out var parsed) ? parsed : null;
        if (args[8] == "auto" && table.Count == 2 && ExactBlock(text, Format(command, args, [], automatic: true)) is { } dynamicBlock)
            return new(UiLanguage.Message("已配置脉络 · 随项目授权自动匹配"), dynamicBlock, Endpoint: endpoint, RelocatedBlock: Relocate([], automatic: true), Command: command);
        if (args[8] is not ("readOnly" or "readWrite") || table.Count != 3 ||
            !table.TryGetValue("enabled_tools", out var t) || t is not TomlArray toolsArray) return new(custom, "");
        var tools = toolsArray.OfType<string>().ToArray();
        if (tools.Length != toolsArray.Count) return new(custom, "");
        if (ExactBlock(text, Format(command, args, tools)) is { } managed)
        {
            var serverLimit = Option("--tools")?.Split(',');
            var limited = EdgeToolCatalog.Tools.Where(t => tools.Contains(t.Name) && (serverLimit is null || serverLimit.Contains(t.Name))
                && (args[8] == "readWrite" || !t.RequiresWrite)).Select(t => t.Name).ToArray();
            return new(UiLanguage.Format("已配置脉络 · {0} 个工具（Edge 管理）", limited.Length), managed, limited, endpoint, Relocate(tools), command);
        }

        // M2 shipped a five-tool project file without a management marker. Only adopt its exact original layout.
        var legacyTools = Environment.GetEnvironmentVariable("DEVTOOLS_HOME");
        if (legacyTools == null && Path.GetPathRoot(command) is { Length: 3 } drive && drive[1] == ':')
            legacyTools = Path.Combine(drive, "app", "devtools"); // Historical per-drive M2 installer layout.
        var legacyExe = legacyTools == null ? null : Path.Combine(legacyTools, "projecthub-edge", "bin", "ProjectHub.Edge.exe");
        if (args.Length == 9 && args[8] == "readWrite" && command.Equals(legacyExe, StringComparison.OrdinalIgnoreCase)
            && tools.SequenceEqual(LegacyTools))
        {
            var legacy = $"""
                [mcp_servers.projecthub]
                command = '{command}'
                args = [
                  "mcp-stdio",
                  "--state", '{args[2]}',
                  "--project", "{args[4]}",
                  "--binding", "{args[6]}",
                  "--mode", "readWrite",
                ]
                enabled_tools = [
                  "list_projects", "get_project_snapshot", "search_project_knowledge",
                  "get_knowledge_history", "submit_knowledge_commit",
                ]
                """.ReplaceLineEndings("\n");
            if (ExactBlock(text, legacy) is { } block) return new(UiLanguage.Message("已配置脉络 · 原有 5 个知识工具"), block, tools, RelocatedBlock: Relocate(tools), Command: command);
        }
        return new(custom, "");
    }

    internal static string? ExactBlock(string text, string block)
    {
        foreach (var candidate in new[] { block, block.Replace("\n", "\r\n") })
        {
            int start = text.IndexOf(candidate, StringComparison.Ordinal);
            if (start < 0 || (start != 0 && text[start - 1] != '\n')) continue;
            var end = start + candidate.Length;
            if (end < text.Length && text[end] is not ('\n' or '\r')) continue;
            if (text.IndexOf(candidate, end, StringComparison.Ordinal) < 0) return candidate;
        }
        return null;
    }

    internal static string Install(LocalBinding binding, string state, EdgeAccessConfig config)
    {
        if (!Directory.Exists(binding.LocalPath)) throw new DirectoryNotFoundException("绑定目录已移动或无法访问。");
        var file = ConfigPath(binding);
        var changed = Edit(file, before =>
        {
            var existing = Inspect(before, binding, state);
            if (existing.Block == "") throw new InvalidOperationException(existing.Label);
            var updated = ReplaceBlock(before, existing.Block, config.CodexToml);
            if (Inspect(updated, binding, state).Block is not { Length: > 0 })
                throw new InvalidOperationException("检测到冲突，请手动核对项目配置。");
            return updated;
        });
        return changed ? "已保存到当前目录的 .codex/config.toml，重新打开项目聊天以加载配置。" : "当前目录已使用所选配置。";
    }

    internal static string ReplaceBlock(string before, string? prior, string block)
    {
        var newline = before.Contains("\r\n") || before.Length == 0 ? "\r\n" : "\n";
        block = block.ReplaceLineEndings(newline);
        return prior is null ? before + (before.Length == 0 || before.EndsWith('\n') ? "" : newline) + block + newline
            : before.Replace(prior, block, StringComparison.Ordinal);
    }

    internal static bool Edit(string file, Func<string, string> transform)
    {
        CheckPath(file);
        var dir = Path.GetDirectoryName(file)!;
        var tmp = Path.Combine(dir, $"config.{Guid.NewGuid():N}.tmp");
        try
        {
            using var source = OpenConfig(file);
            using var original = new MemoryStream();
            source?.CopyTo(original);
            var bytes = original.ToArray();
            var before = Decode(bytes);
            var updated = transform(before);
            if (updated == before) return false;
            Directory.CreateDirectory(dir);
            using (var output = new FileStream(tmp, FileMode.CreateNew, FileAccess.Write, FileShare.None))
            {
                if (bytes.AsSpan().StartsWith(Encoding.UTF8.Preamble)) output.Write(Encoding.UTF8.Preamble);
                output.Write(Utf8.GetBytes(updated));
                output.Flush(flushToDisk: true);
            }
            if (source is null) File.Move(tmp, file);
            else
            {
                if (!File.ReadAllBytes(file).AsSpan().SequenceEqual(bytes)) throw new IOException("配置刚被其他程序更改，请刷新后重试。");
                File.Replace(tmp, file, null);
            }
            return true;
        }
        catch (TomlException) { throw new InvalidDataException("配置含无效或冲突的 TOML，请手动核对。"); }
        finally { if (File.Exists(tmp)) File.Delete(tmp); }
    }
}
